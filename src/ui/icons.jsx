/* size：px；iconify SVG 内建 width/height=1em，经 fontSize 控制尺寸 */
export function Icon({ name, size = 22, color, className = '', style = {} }) {
  const svg = ICONS[name] || ICONS.question
  return (
    <span
      className={`qy-ico ${className}`}
      style={{ fontSize: size, color, display: 'inline-flex', alignItems: 'center', justifyContent: 'center', ...style }}
      dangerouslySetInnerHTML={{ __html: svg }}
      aria-hidden="true"
    />
  )
}

/* 语义着色（对齐 32 枚线性图标集）：支出类橙 / 收入类绿 / 功能类蓝，其余中性 */
export const SEMANTIC = { expense: '#bb7413', income: '#0e715a', func: '#195ea7' }
export function SEMANTIC_COLOR(key) {
  if (key === 'goals') return SEMANTIC.income
  if (['templates', 'loan', 'fx', 'invoice', 'import', 'recurring', 'ledgers', 'review', 'creditCards'].includes(key)) return SEMANTIC.func
  return SEMANTIC.expense
}

